# Helper functions
def get_champion_name(champion_id):
    """Get champion name by ID."""
    return CHAMPIONS.get(champion_id, f"Unknown ({champion_id})")

def get_champion_id(champion_name):
    """Get champion ID by name (case-insensitive)."""
    for cid, cname in CHAMPIONS.items():
        if cname.lower() == champion_name.lower():
            return cid
    return None

def get_champion_by_id(champion_id):
    """Get champion data by ID."""
    return {
        'id': champion_id,
        'name': get_champion_name(champion_id),
        'tags': CHAMPION_TAGS.get(champion_id, [])
    }

def get_all_champions():
    """Get all champions as a list."""
    return [{'id': cid, 'name': cname, 'tags': CHAMPION_TAGS.get(cid, [])} 
            for cid, cname in CHAMPIONS.items()]

def get_champions_by_tag(tag):
    """Get all champions with a specific role tag."""
    return [{'id': cid, 'name': cname, 'tags': CHAMPION_TAGS.get(cid, [])} 
            for cid, cname in CHAMPIONS.items() 
            if tag.lower() in [t.lower() for t in CHAMPION_TAGS.get(cid, [])]]

def get_position_champions(position):
    """Get champions commonly played in a position (for Ironman mode)."""
    # Map positions to champion tags
    position_tags = {
        'top': ['fighter', 'tank'],
        'jungle': ['fighter', 'assassin', 'tank'],
        'mid': ['mage', 'assassin', 'fighter'],
        'adc': ['marksman'],
        'support': ['support', 'mage']
    }
    
    tags = position_tags.get(position.lower(), [])
    if not tags:
        return get_all_champions()
    
    return [c for c in get_all_champions() 
            if any(t.lower() in [ct.lower() for ct in c['tags']] for t in tags)]
